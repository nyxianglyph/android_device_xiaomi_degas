"""Generate the device framework compatibility matrix.

The stock vendor serves HALs (MediaTek, Xiaomi, Dolby, and android.* HALs
under device-specific instance names) that the HyperOS framework declared in
its own matrices. Without them in a framework matrix, check_vintf refuses
the build. This takes the instance list that the VINTF check prints
("in the device manifest but not specified in framework compatibility
matrix") and writes one matrix entry per HAL for them.

usage: tools/gen-framework-matrix.py <build log> > vintf/framework_compatibility_matrix.xml
"""

import collections
import re
import sys

HEADER = 'in the device manifest but not specified in framework compatibility matrix'

# android.hardware.media.c2@1.0::IComponentStore/dolby
hidl = re.compile(r'^([\w.]+)@(\d+\.\d+)::(\w+)/(\S+)$')
# vendor.mediatek.hardware.audio.IMtkAudio/default (@1)
aidl = re.compile(r'^([\w.]+)\.(\w+)/(\S+) \(@(\d+)\)$')


def instances(log):
    text = open(log, errors='replace').read().replace('\r', '\n')
    start = text.index(HEADER)
    for line in text[start:].splitlines()[1:]:
        if not line.startswith('    '):
            break
        yield line.strip()


def main():
    hals = collections.defaultdict(list)
    for inst in instances(sys.argv[1]):
        m = hidl.match(inst)
        if m:
            name, ver, itf, instance = m.groups()
            hals[('hidl', name, ver, itf)].append(instance)
            continue
        m = aidl.match(inst)
        if m:
            name, itf, instance, ver = m.groups()
            hals[('aidl', name, ver, itf)].append(instance)
            continue
        sys.exit(f'cannot parse: {inst}')

    print('<?xml version="1.0" encoding="utf-8"?>')
    print('<!-- Generated by tools/gen-framework-matrix.py, do not edit. -->')
    print('<compatibility-matrix version="1.0" type="framework">')
    for (fmt, name, ver, itf), insts in sorted(hals.items()):
        print(f'    <hal format="{fmt}">')
        print(f'        <name>{name}</name>')
        print(f'        <version>{ver}</version>')
        print('        <interface>')
        print(f'            <name>{itf}</name>')
        for i in sorted(set(insts)):
            print(f'            <instance>{i}</instance>')
        print('        </interface>')
        print('    </hal>')
    print('</compatibility-matrix>')


if __name__ == '__main__':
    main()
